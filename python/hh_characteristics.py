def run_hh_characteristics(year: int, debug: bool) -> None:
    """Orchestrator function to calculate and insert household characteristics.

    The household characteristics created are:
        1. Households by household income category
        2. Households by number of people in each household (size)
        3. Households by number of workers in each household (workers)

    All characteristics are generated by applying ACS data to MGRA level households,
    which are created by the Housing and Households module. Functionality is segmented
    into functions for code encapsulation.

    The following functions are used for households by income category:
        _get_hh_income_inputs - Get MGRA households and ACS tract distributions for
            household income categories
        _validate_hh_income_inputs - Validate the household income category input data
        _create_hh_income - Calculate the household income, control to MGRA households
        _validate_hh_income_outputs - Validate the household income output data
        _insert_hh_income - Insert household income and tract level income
            distributions to the production database

    The following functions are used for households by size:
        _get_hh_size_inputs - Get MGRA households, MGRA household population, and ACS
            tract distributions for household size
        _validate_hh_size_inputs - Validate the household size input data
        _create_hh_size - Calculate the household size, control to MGRA households and
            MGRA household population
        _validate_hh_size_outputs - Validate the household size output data
        _insert_hh_size - Insert household size and tract level size distributions to
            the production database

    The following functions are used for households by workers:
        _get_hh_workers_inputs - Get MGRA households, MGRA population aged 18+, MGRA
            households by size, and ACS tract distributions for households workers
        _validate_hh_workers_inputs - Validate the household workers input data
        _create_hh_workers - Calculate the household workers, control to MGRA
            households, MGRA population aged 18+, and MGRA households by size
        _validate_hh_workers_outputs - Validate the household workers output data
        _insert_hh_workers - Insert household workers and tract level workers
            distributions to the production database

    Args:
        year (int): estimates year
    """
    # Start with household income
    hh_income_inputs = _get_hh_income_inputs(year)
    _validate_hh_income_inputs(year, hh_income_inputs)

    hh_income_outputs = _create_hh_income(hh_income_inputs)
    _validate_hh_income_outputs(hh_income_outputs)

    _insert_hh_income(hh_income_inputs, hh_income_outputs, debug)

    # Then do households by size
    hh_size_inputs = _get_hh_size_inputs(year)
    _validate_hh_size_inputs(year, hh_size_inputs)

    hh_size_outputs = _create_hh_size(hh_size_inputs)
    _validate_hh_size_outputs(hh_size_outputs)

    _insert_hh_size(hh_size_inputs, hh_size_outputs, debug)

    # And finally do households by workers
    hh_workers_inputs = _get_hh_workers_inputs(year)
    _validate_hh_workers_inputs(year, hh_workers_inputs)

    hh_workers_outputs = _create_hh_workers(hh_workers_inputs)
    _validate_hh_workers_outputs(hh_workers_outputs)

    _insert_hh_workers(hh_workers_inputs, hh_workers_outputs, debug)


def _get_hh_income_inputs(year: int) -> dict[str, pd.DataFrame]:
    """Get households and various tract level datas"""
    with utils.ESTIMATES_ENGINE.connect() as con:
        # Store results here
        hh_income_inputs = {}

        # Get MGRA level households. Note we re-use the SQL script from the 'Population
        # by Type' module
        with open(utils.SQL_FOLDER / "pop_type" / "get_mgra_hh.sql") as file:
            hh_income_inputs["hh"] = pd.read_sql_query(
                sql=sql.text(file.read()),
                con=con,
                params={
                    "run_id": utils.RUN_ID,
                    "year": year,
                },  # type: ignore
            ).drop(columns=["jurisdiction"])

        # Tract level household income distributions
        with open(
            utils.SQL_FOLDER / "hh_characteristics" / "get_tract_controls_hh_income.sql"
        ) as file:
            hh_income_inputs["hh_income_tract_controls"] = (
                utils.read_sql_query_fallback(
                    sql=sql.text(file.read()),  # type: ignore
                    con=con,  # type: ignore
                    params={"run_id": utils.RUN_ID, "year": year},
                )
            )

    return hh_income_inputs


